function SetFlag(flagName, enable)
  if flagName == nil then
    error("\227\131\149\227\131\169\227\130\176\229\144\141\227\129\140\228\184\141\230\173\163", 2)
  end
  if enable == true or enable == ON then
    SetSysGlobalFlag(flagName, ON)
  else
    SetSysGlobalFlag(flagName, OFF)
  end
end

